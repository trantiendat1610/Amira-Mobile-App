  const swatch = (path) => `<div class="sw" style="background:var(${cssVar(path)})" title="${cssVar(path)}"></div>`;
  const palette = hues.map((h) => {
    const steps = colorTokens.light.filter((t) => t.path[1] === h && t.path.length === 3);
    return `<div class="row"><span class="label">${h}</span><div class="swatches">${steps.map((t) => `<figure>${swatch(t.path)}<figcaption>${t.path[2]}</figcaption></figure>`).join('')}</div></div>`;
  }).join('\n');
  const sem = semantic.map((t) => `<figure class="semantic">${swatch(t.path)}<figcaption><code>${cssVar(t.path)}</code></figcaption></figure>`).join('\n');
  const typo = typographyTokens.map((t) => {
    const v = plainValue(t, resolveCore);
    const cls = `${cssPrefix}-text-${t.path.slice(1).map(kebab).join('-')}`;
    return `<div class="type-row"><div class="${cls}">The quick brown fox jumps over the lazy dog</div><code>.${cls} · ${v.fontSize}/${v.lineHeight} · ${v.fontWeight}</code></div>`;
  }).join('\n');
